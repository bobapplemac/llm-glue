using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using LlmGlue.Core.Abstractions;

namespace LlmGlue.Core.Generation;

public static partial class ArtifactValidator
{
    public static void Validate(GeneratedArtifact artifact)
    {
        if (artifact.Content.Length == 0) throw new InvalidDataException("Generated artifact is empty.");
        if (artifact.MediaType == "application/json")
        {
            using var document = JsonDocument.Parse(artifact.Content);
            if (!document.RootElement.TryGetProperty("providers", out var providers) || providers.ValueKind != JsonValueKind.Object)
                throw new InvalidDataException("OpenCode artifact has no providers object.");
        }
        else if (artifact.MediaType == "application/yaml")
        {
            var text = Encoding.UTF8.GetString(artifact.Content);
            if (!LiteLlmOwnershipHeader().IsMatch(text))
                throw new InvalidDataException("LiteLLM artifact does not contain the owned model_list document.");
            if (text.Contains("sk-", StringComparison.OrdinalIgnoreCase)) throw new InvalidDataException("Generated artifact appears to contain a literal secret.");
        }
        else throw new InvalidDataException($"Unsupported artifact media type '{artifact.MediaType}'.");
    }

    [GeneratedRegex(@"\A# Generated by LLM Glue r(?:0|[1-9][0-9]*)\. Do not edit\.\nmodel_list:\n", RegexOptions.CultureInvariant)]
    private static partial Regex LiteLlmOwnershipHeader();
}
