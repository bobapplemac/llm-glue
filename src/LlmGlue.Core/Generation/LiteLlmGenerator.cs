using System.Globalization;
using System.Text;
using LlmGlue.Core.Abstractions;
using LlmGlue.Core.Domain;

namespace LlmGlue.Core.Generation;

public sealed class LiteLlmGenerator(
    string apiKeyEnvironment = "LLM_GLUE_PROVIDER_API_KEY",
    string liteLlmNamespace = "llm-glue") : IConfigurationGenerator
{
    public string TargetType => "litellm";

    public ValueTask<GeneratedArtifact> GenerateAsync(DiscoverySnapshot snapshot, CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();
        var builder = new StringBuilder($"# Generated by LLM Glue {ProductInfo.Revision}. Do not edit.\nmodel_list:\n");
        var deployments = GenerationHelpers.Publishable(snapshot).ToArray();
        var duplicateAliases = deployments.GroupBy(x => Alias(x, liteLlmNamespace), StringComparer.Ordinal).Where(x => x.Count() > 1).Select(x => x.Key).Order(StringComparer.Ordinal).ToArray();
        if (duplicateAliases.Length != 0)
            throw new InvalidOperationException($"LiteLLM namespace '{liteLlmNamespace}' contains duplicate normalized aliases: {string.Join(", ", duplicateAliases)}.");
        foreach (var deployment in deployments.OrderBy(x => Alias(x, liteLlmNamespace), StringComparer.Ordinal))
        {
            builder.Append("  - model_name: ").Append(Quote(Alias(deployment, liteLlmNamespace))).Append('\n'
                ).Append("    litellm_params:\n")
                .Append("      model: ").Append(Quote($"openai/{deployment.Identity.Route}")).Append('\n')
                .Append("      api_base: ").Append(Quote(ApiBase(deployment))).Append('\n')
                .Append("      api_key: ").Append(Quote($"os.environ/{apiKeyEnvironment}")).Append('\n');
            var context = deployment.EffectiveContext?.Value ?? deployment.NativeContext?.Value;
            if (context is > 0) builder.Append("    model_info:\n      max_input_tokens: ").Append(context.Value.ToString(CultureInfo.InvariantCulture)).Append('\n');
        }
        return ValueTask.FromResult(GenerationHelpers.Artifact("application/yaml", builder.ToString()));
    }

    public static string Alias(ModelDeployment deployment, string liteLlmNamespace = "llm-glue") => GenerationHelpers.Slug(liteLlmNamespace, deployment.Identity.ModelId);
    private static string ApiBase(ModelDeployment deployment)
    {
        var endpoint = deployment.Identity.SourceEndpoint!.TrimEnd('/');
        return endpoint.EndsWith("/v1", StringComparison.OrdinalIgnoreCase) ? endpoint : endpoint + "/v1";
    }
    private static string Quote(string value) => $"'{value.Replace("'", "''", StringComparison.Ordinal)}'";
}
