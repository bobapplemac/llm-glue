    [Fact]
    public async Task OpenCodeMatchesGoldenAndContainsVerifiedVariantsOnly()
    {
        var artifact = await new OpenCodeGenerator().GenerateAsync(Snapshot(), TestContext.Current.CancellationToken);
        ArtifactValidator.Validate(artifact);
        using var actual = JsonDocument.Parse(artifact.Content);
        using var expected = JsonDocument.Parse(File.ReadAllBytes(Path.Combine(AppContext.BaseDirectory, "fixtures", "golden", "opencode.json")));
        Assert.True(JsonElement.DeepEquals(expected.RootElement, actual.RootElement));
        Assert.DoesNotContain("api_key", Encoding.UTF8.GetString(artifact.Content), StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public async Task LiteLlmMatchesGoldenAndUsesEnvironmentSecretReference()
    {
        var artifact = await new LiteLlmGenerator().GenerateAsync(Snapshot(), TestContext.Current.CancellationToken);
        ArtifactValidator.Validate(artifact);
        var expected = File.ReadAllText(Path.Combine(AppContext.BaseDirectory, "fixtures", "golden", "litellm.yaml")).ReplaceLineEndings("\n");
        Assert.Equal(expected, Encoding.UTF8.GetString(artifact.Content));
        Assert.DoesNotContain("sk-", expected, StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public void LiteLlmValidatorAcceptsArtifactsFromEarlierProductRevisions()
    {
        var content = Encoding.UTF8.GetBytes("# Generated by LLM Glue r1. Do not edit.\nmodel_list:\n");
        var artifact = new GeneratedArtifact("application/yaml", content, Convert.ToHexStringLower(System.Security.Cryptography.SHA256.HashData(content)), 1);

        ArtifactValidator.Validate(artifact);
    }

    [Fact]
    public async Task CentralOpenCodeArtifactRoutesStableAliasThroughLiteLlm()
    {
        var artifact = await new OpenCodeGenerator(new Uri("https://litellm.example.test"), "test-inference-key")
            .GenerateAsync(Snapshot(), TestContext.Current.CancellationToken);
        ArtifactValidator.Validate(artifact);
        using var json = JsonDocument.Parse(artifact.Content);
        using var expected = JsonDocument.Parse(File.ReadAllBytes(Path.Combine(AppContext.BaseDirectory, "fixtures", "golden", "opencode-central.json")));
        Assert.True(JsonElement.DeepEquals(expected.RootElement, json.RootElement));
        var provider = json.RootElement.GetProperty("providers").GetProperty("llm-glue");
        Assert.Equal("https://litellm.example.test/v1", provider.GetProperty("settings").GetProperty("baseURL").GetString());
        Assert.Equal("test-inference-key", provider.GetProperty("settings").GetProperty("apiKey").GetString());
        Assert.False(provider.TryGetProperty("env", out _));
        Assert.Equal("llama-cpp-lab-qwen-model", provider.GetProperty("models").GetProperty("qwen-model").GetProperty("modelID").GetString());
        Assert.DoesNotContain("integration-secret", Encoding.UTF8.GetString(artifact.Content), StringComparison.Ordinal);
    }

    [Fact]
    public async Task DirectOllamaArtifactDisablesNativeDuplicateButCentralArtifactDoesNot()
    {
        var ollama = Qualified() with
        {
            Identity = Qualified().Identity with
            {
                ProviderId = "ollama",
                InstanceId = "windows",
                SourceEndpoint = "http://127.0.0.1:11434"
            }
        };
        var snapshot = DiscoverySnapshot.Create(DateTimeOffset.UnixEpoch, [ollama]);
        var direct = await new OpenCodeGenerator().GenerateAsync(snapshot, TestContext.Current.CancellationToken);
        using var directJson = JsonDocument.Parse(direct.Content);
        Assert.Equal("ollama", Assert.Single(directJson.RootElement.GetProperty("disabled_providers").EnumerateArray()).GetString());

        var central = await new OpenCodeGenerator(new Uri("https://litellm.example.test"), "test-inference-key").GenerateAsync(snapshot, TestContext.Current.CancellationToken);
        using var centralJson = JsonDocument.Parse(central.Content);
        Assert.False(centralJson.RootElement.TryGetProperty("disabled_providers", out _));
    }

    [Fact]
    public async Task CentralOpenCodeArtifactCanUseClientEnvironmentWhenEmbeddingIsDisabled()
    {
        var artifact = await new OpenCodeGenerator(new Uri("https://litellm.example.test"), embedInferenceApiKey: false)
            .GenerateAsync(Snapshot(), TestContext.Current.CancellationToken);
        using var json = JsonDocument.Parse(artifact.Content);
        var provider = json.RootElement.GetProperty("providers").GetProperty("llm-glue");
        Assert.Equal("{env:LLM_GLUE_INFERENCE_API_KEY}", provider.GetProperty("settings").GetProperty("apiKey").GetString());
        Assert.Equal("LLM_GLUE_INFERENCE_API_KEY", provider.GetProperty("env")[0].GetString());
    }

    [Fact]
    public async Task DoesNotPublishUnavailableOrInvalidDeployments()
    {
        var deployment = Qualified() with { Status = DeploymentStatus.Unavailable };
        var artifact = await new OpenCodeGenerator().GenerateAsync(DiscoverySnapshot.Create(DateTimeOffset.UnixEpoch, [deployment]), TestContext.Current.CancellationToken);
        using var json = JsonDocument.Parse(artifact.Content);
        Assert.Empty(json.RootElement.GetProperty("providers").EnumerateObject());
    }

    [Fact]
    public async Task PublishesDeploymentWithUnknownCapabilitiesWithoutInventingClaims()
    {
        var deployment = Qualified() with
        {
            Capabilities = Qualified().Capabilities with
            {
                TextInput = new(SupportState.Unknown, []),
                TextOutput = new(SupportState.Unknown, []),
                Tools = new(SupportState.Unknown, []),
                Reasoning = new(ReasoningModeKind.Unknown, [])
            }
        };
        var snapshot = DiscoverySnapshot.Create(DateTimeOffset.UnixEpoch, [deployment]);
        var artifact = await new OpenCodeGenerator().GenerateAsync(
            snapshot,
            TestContext.Current.CancellationToken);
        using var json = JsonDocument.Parse(artifact.Content);
        var capabilities = json.RootElement.GetProperty("providers").GetProperty("llm-glue")
            .GetProperty("models").GetProperty("qwen-model").GetProperty("capabilities");
        Assert.False(capabilities.TryGetProperty("input", out _));
        Assert.False(capabilities.TryGetProperty("output", out _));
        Assert.False(capabilities.TryGetProperty("tools", out _));
        Assert.False(capabilities.TryGetProperty("reasoning", out _));

        var liteLlm = Encoding.UTF8.GetString((await new LiteLlmGenerator().GenerateAsync(snapshot, TestContext.Current.CancellationToken)).Content);
        Assert.Contains("llama-cpp-lab-qwen-model", liteLlm, StringComparison.Ordinal);
    }

    [Fact]
    public async Task AggregatesSourcesIntoDefaultNamespaceAndSupportsOrderedOverrides()
    {
        var first = Qualified();
        var second = Qualified() with
        {
            Identity = Qualified().Identity with
            {
                ProviderId = "ollama",
                InstanceId = "workstation",
                ModelId = "other-model",
                DisplayName = "Other Model",
                Route = "other-model",
                SourceEndpoint = "http://127.0.0.1:11434"
            }
        };
        var snapshot = DiscoverySnapshot.Create(DateTimeOffset.UnixEpoch, [first, second]);

        var aggregated = await new OpenCodeGenerator(new Uri("https://litellm.example.test"), "test-key")
            .GenerateAsync(snapshot, TestContext.Current.CancellationToken);
        using (var json = JsonDocument.Parse(aggregated.Content))
        {
            var providers = json.RootElement.GetProperty("providers");
            var provider = Assert.Single(providers.EnumerateObject());
            Assert.Equal("llm-glue", provider.Name);
            Assert.Equal(2, provider.Value.GetProperty("models").EnumerateObject().Count());
        }

        var split = await new OpenCodeGenerator(
                new Uri("https://litellm.example.test"),
                "test-key",
                defaultNamespace: "models",
                namespaceOverrides: [new("workstation", "ollama", "workstation"), new("ignored", "ollama", null)])
            .GenerateAsync(snapshot, TestContext.Current.CancellationToken);
        using var splitJson = JsonDocument.Parse(split.Content);
        Assert.Equal(["models", "workstation"], splitJson.RootElement.GetProperty("providers").EnumerateObject().Select(x => x.Name).ToArray());
    }

    [Fact]
    public async Task RejectsDuplicateModelIdsWithinOneNamespace()
    {
        var duplicate = Qualified() with
        {
            Identity = Qualified().Identity with { ProviderId = "ollama", InstanceId = "other", Route = "other-route" }
        };
        var generator = new OpenCodeGenerator(new Uri("https://litellm.example.test"), "test-key");
        var error = await Assert.ThrowsAsync<InvalidOperationException>(() => generator.GenerateAsync(
            DiscoverySnapshot.Create(DateTimeOffset.UnixEpoch, [Qualified(), duplicate]), TestContext.Current.CancellationToken).AsTask());
        Assert.Contains("duplicate model IDs", error.Message, StringComparison.Ordinal);
    }

    [Fact]
