using System.Net.Security;
using LlmGlue.Core.Configuration;
using LlmGlue.Core.Security;
using LlmGlue.Security;

namespace LlmGlue.Tests;

public sealed class TlsTests
{
    [Fact]
    public void DefaultServerUsesAutoGeneratedHttpsCertificate()
    {
        var directory = CreateDirectory();
        var config = Path.Combine(directory, "llm-glue.conf");
        File.WriteAllText(config, "[roles]\nagent=false\nserver=true\nclient=false\n");
        try
        {
            var options = TomlConfigLoader.Load(config);
            Assert.Equal("https", options.Server.Listen.Scheme);
            Assert.True(options.Server.TlsAutoGenerate);
            using var tls = ServerTlsCertificateManager.LoadOrCreate(options);
            Assert.True(File.Exists(tls.CertificatePath));
            Assert.True(File.Exists(tls.PrivateKeyPath));
            Assert.True(tls.Certificate.NotAfter.ToUniversalTime() > DateTime.UtcNow.AddYears(29));
            Assert.Equal(64, tls.PublicKeySha256.Length);
        }
        finally { Directory.Delete(directory, recursive: true); }
    }

    [Fact]
    public void LoadsPasswordProtectedPfxFromFile()
    {
        var directory = CreateDirectory();
        var pfx = Path.Combine(directory, "server.pfx");
        var generatedConfig = Path.Combine(directory, "generate.conf");
        File.WriteAllText(generatedConfig, $$"""
            [roles]
            agent = false
            server = true
            client = false
            [server]
            tls_certificate_path = "{{pfx.Replace("\\", "/", StringComparison.Ordinal)}}"
            tls_certificate_password = "test-password"
            """);
        try
        {
            using var generated = ServerTlsCertificateManager.LoadOrCreate(TomlConfigLoader.Load(generatedConfig));
            var config = Path.Combine(directory, "pfx.conf");
            File.WriteAllText(config, $$"""
                [roles]
                agent = false
                server = true
                client = false
                [server]
                listen = "https://127.0.0.1:8765"
                tls_auto_generate = false
                tls_certificate_path = "{{pfx.Replace("\\", "/", StringComparison.Ordinal)}}"
                tls_certificate_password = "test-password"
                """);
            using var loaded = ServerTlsCertificateManager.LoadOrCreate(TomlConfigLoader.Load(config));
            Assert.True(loaded.Certificate.HasPrivateKey);
            Assert.Equal(generated.PublicKeySha256, loaded.PublicKeySha256);
        }
        finally { Directory.Delete(directory, recursive: true); }
    }

    [Fact]
    public void PublicKeyPinIsAuthoritativeForValidAndInvalidCertificates()
    {
        var directory = CreateDirectory();
        var config = Path.Combine(directory, "llm-glue.conf");
        File.WriteAllText(config, "[roles]\nagent=false\nserver=true\nclient=false\n");
        try
        {
            using var tls = ServerTlsCertificateManager.LoadOrCreate(TomlConfigLoader.Load(config));
            Assert.True(TlsHttpClientFactory.ValidateServerCertificate(tls.Certificate, SslPolicyErrors.RemoteCertificateChainErrors, false, tls.PublicKeySha256));
            Assert.False(TlsHttpClientFactory.ValidateServerCertificate(tls.Certificate, SslPolicyErrors.RemoteCertificateChainErrors, false, new string('0', 64)));
            Assert.True(TlsHttpClientFactory.ValidateServerCertificate(tls.Certificate, SslPolicyErrors.None, false, tls.PublicKeySha256));
            Assert.False(TlsHttpClientFactory.ValidateServerCertificate(tls.Certificate, SslPolicyErrors.None, false, new string('0', 64)));
            Assert.True(TlsHttpClientFactory.ValidateServerCertificate(tls.Certificate, SslPolicyErrors.RemoteCertificateChainErrors, true, null));
        }
        finally { Directory.Delete(directory, recursive: true); }
    }

    [Theory]
    [InlineData("api.example.test", true)]
    [InlineData("node.example.test", true)]
    [InlineData("deep.node.example.test", true)]
    [InlineData("other.test", false)]
    [InlineData(null, false)]
    public void SniPatternsRestrictNames(string? name, bool expected)
    {
        Assert.Equal(expected, ServerTlsCertificateManager.MatchesServerName(["api.example.test", "*.example.test"], name));
    }

    [Fact]
    public void RejectsAmbiguousClientTlsTrustPolicy()
    {
        var path = Path.Combine(CreateDirectory(), "llm-glue.conf");
        File.WriteAllText(path, $$"""
            [roles]
            agent = false
            server = false
            client = true
            [client]
            source = "https://example.test:8765"
            token = "test"
            allow_invalid_server_certificate = true
            trusted_server_public_key_sha256 = "{{new string('a', 64)}}"
            """);
        try { Assert.Contains("mutually exclusive", Assert.Throws<ConfigurationException>(() => TomlConfigLoader.Load(path)).Message); }
        finally { Directory.Delete(Path.GetDirectoryName(path)!, recursive: true); }
    }

    private static string CreateDirectory()
    {
        var path = Path.Combine(Path.GetTempPath(), $"llm-glue-tls-{Guid.NewGuid():N}");
        Directory.CreateDirectory(path);
        return path;
    }
}
